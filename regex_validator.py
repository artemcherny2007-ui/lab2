import re
from typing import List

# Регулярное выражение для поиска российских индексов.
# \b : Граница слова, чтобы не захватить часть длинного числа.
# (?:RU-)? : префикс страны с дефисом(мб удалить надо будет)
# [1-9] : первая цифра != 0
# \d{5} : 5 цифр (любые от 0 до 9)
# \b : Граница слова
POSTAL_CODE_PATTERN = re.compile(r'\b(?:RU-)?[1-9]\d{5}\b')


def find_postal_codes(text: str) -> List[str]:
    """
    Ищет все валидные почтовые индексы России в переданном тексте.
    Возвращает список найденных индексов в строковом формате.
    """
    if not text:
        return []

    # re.findall возвращает список всех совпадений
    return POSTAL_CODE_PATTERN.findall(text)